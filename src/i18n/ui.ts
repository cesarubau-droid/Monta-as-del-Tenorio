/** Replaces {key} tokens: fmt('Up to {n}', { n: 7 }) */
export function fmt(str: string, vars: Record<string, string | number>): string {
  return str.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
